export function translate(language, key, values = {}) {
  const text = messages[language]?.[key] ?? messages.en[key];
  if (text === undefined) throw new Error(`Missing translation: ${key}`);
  return text.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
}

export function escapeHTML(value) {
  return String(value).replace(/[&<>"']/g, char => ({
    "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
  })[char]);
}

export function progress(job) {
  if (!job) return 0;
  if (!job.total) return 0;
  const processed = job.completed.length + (job.skipped?.length ?? 0);
  return Math.min(job.state === "completed" ? 100 : 99, Math.max(0, Math.round(processed / job.total * 100)));
}
